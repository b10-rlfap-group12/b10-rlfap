#!/usr/bin/env python3
from PIL import Image, ImageDraw, ImageFont
from pathlib import Path
import subprocess, shutil, math

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'demo' / 'frames'
OUT.mkdir(parents=True, exist_ok=True)
for p in OUT.glob('*.png'): p.unlink()
W, H, FPS = 1280, 720, 30
navy, cyan, white, muted, green, panel = '#071A33', '#00B4D8', '#F8F9FA', '#AFC1D6', '#62D39B', '#102C4A'
font_path = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
mono_path = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'
def font(size, mono=False): return ImageFont.truetype(mono_path if mono else font_path, size)
def text(draw, xy, s, size=24, fill=white, mono=False, anchor=None): draw.text(xy, s, font=font(size, mono), fill=fill, anchor=anchor)
def wrap_lines(s, n): return [s[i:i+n] for i in range(0, len(s), n)]
def terminal(draw, x, y, w, h, lines, cursor=True):
    draw.rounded_rectangle((x,y,x+w,y+h), 14, fill='#061321', outline='#2B5878', width=2)
    draw.rectangle((x,y,x+w,y+34), fill='#0D243A')
    for i,c in enumerate(['#FF6B6B','#FFD166','#62D39B']): draw.ellipse((x+15+i*22,y+11,x+27+i*22,y+23),fill=c)
    yy=y+52
    for line, color in lines:
        text(draw,(x+24,yy),line,20,color,mono=True); yy+=31
    if cursor: draw.rectangle((x+24,yy+2,x+38,yy+24),fill=cyan)
def draw_plot(draw, path, box, label):
    if path.exists():
        im=Image.open(path).convert('RGB'); im.thumbnail((box[2]-box[0]-24,box[3]-box[1]-48))
        px=box[0]+(box[2]-box[0]-im.width)//2; py=box[1]+32
        draw.rounded_rectangle(box,12,fill='white',outline='#DDE2E5',width=2); draw._image.paste(im,(px,py))
        text(draw,(box[0]+16,box[1]+10),label,17,navy)
    else:
        draw.rounded_rectangle(box,12,fill='white',outline='#DDE2E5',width=2); text(draw,(box[0]+20,box[1]+20),'Plot generated by plot.py',20,navy)
def frame(scene, t):
    im=Image.new('RGB',(W,H),navy); d=ImageDraw.Draw(im)
    d.rectangle((0,0,W,8),fill=cyan)
    if scene==0:
        text(d,(W//2,145),'B10 · LIVE PROJECT DEMO',54,white,anchor='mm')
        text(d,(W//2,240),'Radio Link Frequency Assignment',36,cyan,anchor='mm')
        text(d,(W//2,330),'MiniZinc · Gecode · CELAR validation',28,muted,anchor='mm')
        d.rounded_rectangle((315,420,965,520),18,fill=panel,outline=cyan,width=2)
        text(d,(W//2,454),'Group 12  |  CSE  |  Even Section',24,white,anchor='mm')
        text(d,(W//2,490),'Saif Al Sabah · Fokrul Islam',22,muted,anchor='mm')
    elif scene==1:
        text(d,(48,48),'01  REPRODUCIBLE SETUP',30,white); text(d,(48,92),'Generate the same instances from a recorded seed.',20,muted)
        lines=[('$ python src/gen_instances.py --count 10 --seed 2026',cyan),('wrote instance_01_20vars.dzn  (seed=2026)',green),('wrote instance_10_110vars.dzn (seed=2035)',green),('saved 10 deterministic .dzn instances',white)]
        terminal(d,70,170,1140,350,lines)
    elif scene==2:
        text(d,(48,48),'02  OFFICIAL CELAR VALIDATION',30,white); text(d,(48,92),'Public benchmark schema + solver validation.',20,muted)
        lines=[('$ python src/validate_celar.py --solver Gecode --time-limit 30',cyan),('validated=10/10; nonzero_objective=10/10',green),('saved results/celar_validation.csv',white)]
        terminal(d,70,170,1140,250,lines)
        d.rounded_rectangle((300,470,980,610),18,fill='#123B2D',outline=green,width=2)
        text(d,(W//2,510),'10 / 10  VALIDATED',42,green,anchor='mm'); text(d,(W//2,565),'non-zero objectives · feasible benchmark solutions',20,white,anchor='mm')
    elif scene==3:
        text(d,(48,48),'03  SOLVER EXPERIMENT',30,white); text(d,(48,92),'Search + backend comparison: Gecode vs HiGHS.',20,muted)
        lines=[('$ python src/run.py --time-limit 10',cyan),('model_first_fail / Gecode / instance_10_110vars.dzn',white),('model_input_order / Gecode / instance_10_110vars.dzn',white),('model_default / HiGHS / instance_10_110vars.dzn',white),('saved results/results.csv (30 runs)',green)]
        terminal(d,70,145,1140,300,lines)
        d.rounded_rectangle((70,500,570,625),14,fill=panel); d.rounded_rectangle((610,500,1210,625),14,fill=panel)
        text(d,(90,530),'OPTIMAL rows',18,muted); text(d,(90,570),'30',48,cyan)
        text(d,(630,530),'objective range',18,muted); text(d,(630,570),'0–26',48,green)
    elif scene==4:
        text(d,(48,42),'04  RESULTS & PLOTS',30,white); text(d,(48,84),'Runtime and weighted-interference views.',20,muted)
        draw_plot(d,ROOT/'results/plots/solve_time_by_scale.png',(45,135,615,650),'solve_time_by_scale.png')
        draw_plot(d,ROOT/'results/plots/objective_by_scale.png',(665,135,1235,650),'objective_by_scale.png')
    elif scene==5:
        text(d,(W//2,120),'DEMO COMPLETE',52,white,anchor='mm'); text(d,(W//2,210),'Reproducible model · validated data · measurable results',28,cyan,anchor='mm')
        text(d,(W//2,330),'Run  |  Validate  |  Analyse  |  Plot',32,white,anchor='mm')
        text(d,(W//2,470),'B10 RLFAP · Group 12',24,muted,anchor='mm')
        text(d,(W//2,535),'README · paper draft · CSV · plots · CELAR evidence',21,muted,anchor='mm')
    return im

scenes=[(0,3),(1,5),(2,5),(3,6),(4,7),(5,3)]
idx=0
for scene,dur in scenes:
    n=int(dur*FPS)
    for i in range(n):
        frame(scene,i/FPS).save(OUT/f'{idx:05d}.png'); idx+=1
video=ROOT/'demo'/'B10_RLFAP_Live_Demo.mp4'
subprocess.run(['ffmpeg','-y','-framerate',str(FPS),'-i',str(OUT/'%05d.png'),'-c:v','libx264','-pix_fmt','yuv420p','-movflags','+faststart',str(video)],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
print(video)
